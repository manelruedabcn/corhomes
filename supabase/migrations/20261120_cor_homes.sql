-- COR HOMES · Supabase schema (applied 2026-11-20 to project "COR HOMES", ref uoyiufekbtmtuwpuattq)
-- Tables mirror the original D1/SQLite schema. The web server only holds the publishable key:
-- public reads go through RLS + column grants, writes through SECURITY DEFINER functions.
-- Admin functions require COR_SERVER_SECRET; only its SHA-256 is stored in private.config.

create extension if not exists pgcrypto with schema extensions;

create table public.properties (
  id bigint generated by default as identity primary key,
  slug text unique not null, title text not null, city text not null,
  operation text not null check (operation in ('venta','alquiler')),
  price numeric not null, area numeric not null, rooms integer not null,
  description text not null, images text not null default '[]',
  status text not null check (status in ('disponible','reservado','vendido','borrador','off_market')),
  private_token text unique
);
create table public.leads (
  id bigint generated by default as identity primary key,
  created text not null, name text not null, email text not null,
  phone text, message text, property_id bigint
);
create index leads_email_created on public.leads(email, created);
alter table public.properties enable row level security;
alter table public.leads enable row level security;
revoke all on public.properties, public.leads from anon, authenticated;

grant select (id, slug, title, city, operation, price, area, rooms, description, images, status) on public.properties to anon;
create policy "public listings" on public.properties for select to anon using (status not in ('borrador','off_market'));
create view public.public_properties with (security_invoker = true) as
  select id, slug, title, city, operation, price, area, rooms, description, images, status from public.properties;
grant select on public.public_properties to anon;

create schema private;
revoke all on schema private from public, anon, authenticated;
create table private.config (key text primary key, value text not null);
